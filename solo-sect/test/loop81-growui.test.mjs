/* loop81 成長分層介面：純顯示、固定基準、狀態分辨、閘門 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createState, tick } from '../src/sim.mjs';
import { ARTS } from '../src/data.mjs';
import { polySvg, growthHtml, artStatus, dailyGrowth, axisVals, AXES, catHtml } from '../src/growui.mjs';
const mk = () => { const s = createState(7, { kind: 'custom', answers: Array(9).fill(0), grow: true }); for (let i = 0; i < 800; i++) tick(s, 0.25); return s; };
const A = (id) => ARTS.find((a) => a.id === id);
test('畫面不改世界與亂數', () => { const s = mk(), before = JSON.stringify(s), memo = {};
  for (const d of s.ds) for (let k = 0; k < 3; k++) growthHtml(d, memo, s.day + k, s.t + k, true);
  assert.equal(JSON.stringify(s), before); });
test('重繪／切換不影響後續模擬', () => { const a = mk(), b = mk(), memo = {};
  for (let i = 0; i < 400; i++) { tick(a, 0.25); tick(b, 0.25); if (i % 7 === 0) for (const d of b.ds) growthHtml(d, memo, b.day, b.t, true); }
  assert.equal(JSON.stringify(a), JSON.stringify(b)); });
test('固定基準：同數值同位置，不隨他人縮放', () => { const s = mk(), [x, y] = s.ds; const sx = polySvg(x); y.skills.palm = 99; assert.equal(polySvg(x), sx); });
test('超出基準照實標示', () => { const s = mk(), d = s.ds[0]; d.skills.palm = 130; const h = growthHtml(d, {}, 1, 0, true); assert.match(h, /掌 130\.0▲/); assert.match(h, /超出顯示範圍：掌/); });
test('五軸固定順序；生命另列；無面積', () => { assert.deepEqual(AXES.map((x) => x.name), ['掌', '腿', '力氣', '腳力', '調息']); const h = growthHtml(mk().ds[0], {}, 1, 0, true); assert.match(h, /生命 \d+\/100/); assert.doesNotMatch(h, /面積/); });
test('換日才合併提示，且只有真成長', () => { const s = mk(), d = s.ds[0], m = {}; dailyGrowth(m, d, 1, 0); assert.equal(m[d.id].msg, '');
  dailyGrowth(m, d, 2, 10); assert.equal(m[d.id].msg, ''); assert.equal(m[d.id].anim, false);
  d.skills.palm += 2; dailyGrowth(m, d, 3, 20); assert.match(m[d.id].msg, /掌 \+2\.0/); assert.equal(m[d.id].anim, true);
  dailyGrowth(m, d, 3, 30); assert.equal(m[d.id].anim, false); assert.match(m[d.id].msg, /掌 \+2\.0/); });
test('個別武學狀態分辨', () => { const s = mk(), d = s.ds[0], a = A('basicFist'), r = d.arts.basicFist;
  r.xp = 10; r.btCd = 0; assert.equal(artStatus(d, a, s.t).st, 'acc');
  r.btCd = s.t + 600; assert.equal(artStatus(d, a, s.t).st, 'cd');
  r.btCd = 0; r.xp = 54.9; r.bt1 = false; assert.equal(artStatus(d, a, s.t).st, 'stuck'); assert.match(artStatus(d, a, s.t).text, /需打坐突破/);
  delete d.arts.wavePalm; assert.equal(artStatus(d, A('wavePalm'), s.t).st, 'req'); });
test('來源理由取自真實結算', () => { const s = mk(), d = s.ds[0]; d.arts.basicFist.gm = { e: 20 }; d.arts.wavePalm ??= { xp: 0 }; d.arts.wavePalm.xp = 5; const h = growthHtml(d, {}, 1, s.t, true); assert.match(h, /拳掌底子：入門修練 ×1\.\d\d/); });
test('未支援門類只標示', () => { assert.match(catHtml(mk().ds[0]), /尚未支援：棍棒/); });
test('主畫面閘門與減少動態', () => { const m = readFileSync(new URL('../src/main.mjs', import.meta.url), 'utf8'), c = readFileSync(new URL('../style.css', import.meta.url), 'utf8');
  assert.match(m, /S\.grow \? growthHtml\(cur, GMEMO/); assert.match(c, /prefers-reduced-motion: reduce\)\{\.poly-grow \.poly-shape\{animation:none/); });
